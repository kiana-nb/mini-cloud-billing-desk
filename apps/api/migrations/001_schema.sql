-- Schema for the mini-cloud billing desk.
-- Every business rule that can be expressed in the database is expressed here,
-- so a bug in application code cannot break it. Rules are tagged [R#] and listed in the README.

create extension if not exists btree_gist;

-- ---------------------------------------------------------------------------
-- Testable clock. All billing logic reads app_now(), never now().
-- The clock either ticks with real time (virtual_base + elapsed real time) or is frozen.
-- It can only move forward [R1].
-- ---------------------------------------------------------------------------
create table app_clock (
  id           boolean primary key default true check (id),
  virtual_base timestamptz not null,
  real_base    timestamptz not null,
  frozen       boolean not null default false
);
insert into app_clock (virtual_base, real_base) values (now(), now());

create function app_now() returns timestamptz
language sql stable as $$
  select case when frozen then virtual_base else virtual_base + (now() - real_base) end from app_clock
$$;

create function app_clock_forward_only() returns trigger
language plpgsql as $$
begin
  if (case when new.frozen then new.virtual_base else new.virtual_base + (now() - new.real_base) end)
     < (case when old.frozen then old.virtual_base else old.virtual_base + (now() - old.real_base) end) then
    raise exception 'the clock can only move forward' using errcode = 'P0001';
  end if;
  return new;
end $$;
create trigger app_clock_forward_only before update on app_clock
  for each row execute function app_clock_forward_only();

-- A whole UTC hour: seconds since epoch divisible by 3600 (immutable, timezone independent).
create function is_whole_hour(t timestamptz) returns boolean
language sql immutable as $$ select extract(epoch from t)::numeric % 3600 = 0 $$;

-- ---------------------------------------------------------------------------
-- Staff and roles
-- ---------------------------------------------------------------------------
create type staff_role as enum ('owner', 'support', 'viewer');

create table staff_users (
  id            uuid primary key default gen_random_uuid(),
  email         text not null unique,
  name          text not null,
  role          staff_role not null,
  password_hash text not null,
  created_at    timestamptz not null default now()
);

create table staff_sessions (
  token_hash text primary key,
  staff_id   uuid not null references staff_users (id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);

-- ---------------------------------------------------------------------------
-- Customers and their statuses. A customer can hold several statuses at once;
-- each status has a history, and at most one open row per status [R2].
-- ---------------------------------------------------------------------------
create table customers (
  id         uuid primary key default gen_random_uuid(),
  name       text not null check (length(trim(name)) between 1 and 200),
  email      text not null unique check (email like '%_@_%'),
  created_at timestamptz not null default app_now()
);

create type customer_status as enum ('verified', 'payment_notice', 'suspended');

create table customer_statuses (
  id          bigserial primary key,
  customer_id uuid not null references customers (id),
  status      customer_status not null,
  set_at      timestamptz not null default app_now(),
  cleared_at  timestamptz,
  reason      text not null default '',
  check (cleared_at is null or cleared_at >= set_at)
);
create unique index customer_statuses_one_open on customer_statuses (customer_id, status) where cleared_at is null;

-- ---------------------------------------------------------------------------
-- Prices. A price applies from a whole hour on. Hours already charged keep the
-- price that was stored on their ledger row.
-- ---------------------------------------------------------------------------
create type resource_kind as enum ('server', 'ip');

create table prices (
  id              serial primary key,
  resource        resource_kind not null,
  amount_per_hour bigint not null check (amount_per_hour >= 0),
  effective_from  timestamptz not null check (is_whole_hour(effective_from)),
  created_at      timestamptz not null default app_now(),
  unique (resource, effective_from)
);
insert into prices (resource, amount_per_hour, effective_from) values
  ('server', 100, '2000-01-01T00:00:00Z'),
  ('ip',      20, '2000-01-01T00:00:00Z');

-- ---------------------------------------------------------------------------
-- Servers. `id` is generated by us before the infrastructure is called and is sent
-- to the infrastructure as the server's tag, so we can always find "our" server
-- even when the infrastructure lies about having created it.
-- ---------------------------------------------------------------------------
create type server_status as enum ('pending', 'provisioning', 'running', 'terminating', 'terminated', 'failed');

create table servers (
  id              uuid primary key default gen_random_uuid(),
  customer_id     uuid not null references customers (id),
  name            text not null check (name ~ '^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$'),
  status          server_status not null default 'pending',
  infra_id        text unique,                        -- [R3] one infrastructure server is tracked at most once
  idempotency_key text not null,
  created_at      timestamptz not null default app_now(),
  running_at      timestamptz,
  terminate_requested_at timestamptz,
  terminated_at   timestamptz,
  restorable_until timestamptz,
  -- worker bookkeeping (real time, not billing time)
  attempts        int not null default 0,
  next_attempt_at timestamptz not null default now(),
  lease_until     timestamptz,
  infra_linked_at timestamptz,
  last_error      text,
  unique (customer_id, idempotency_key),              -- [R4] a retried create request creates one server
  unique (id, customer_id)                            -- target of the composite FK below
);
create index servers_status_idx on servers (status, next_attempt_at);
create index servers_customer_idx on servers (customer_id);
create index servers_name_idx on servers (name text_pattern_ops);

-- A server's owner never changes; the IP and ledger rows rely on it [R5].
create function servers_customer_immutable() returns trigger
language plpgsql as $$
begin
  if new.customer_id <> old.customer_id then
    raise exception 'a server cannot change customer' using errcode = 'P0001';
  end if;
  return new;
end $$;
create trigger servers_customer_immutable before update on servers
  for each row execute function servers_customer_immutable();

-- Periods in which the server actually ran. Only these are billed.
-- No two periods of one server overlap [R6].
create table server_usage (
  id        bigserial primary key,
  server_id uuid not null references servers (id),
  during    tstzrange not null check (not isempty(during) and not lower_inf(during) and lower_inc(during) and not upper_inc(during)),
  exclude using gist (server_id with =, during with &&)
);
create unique index server_usage_one_open on server_usage (server_id) where upper_inf(during);

-- ---------------------------------------------------------------------------
-- IP addresses: a fixed pool, and the history of who held each one.
-- ---------------------------------------------------------------------------
create table ip_addresses (
  id      serial primary key,
  address inet not null unique
);
insert into ip_addresses (address)
  select ('203.0.113.' || n)::inet from generate_series(10, 59) as n;

create table ip_assignments (
  id          bigserial primary key,
  ip_id       int not null references ip_addresses (id),
  server_id   uuid not null,
  customer_id uuid not null,
  during      tstzrange not null check (not isempty(during) and not lower_inf(during) and lower_inc(during) and not upper_inc(during)),
  request_key text,
  -- [R7] the customer on an assignment is always the server's customer
  foreign key (server_id, customer_id) references servers (id, customer_id),
  -- [R8] an IP is held by at most one server (and so one customer) at any moment
  exclude using gist (ip_id with =, during with &&),
  unique (server_id, request_key)
);
create index ip_assignments_server_idx on ip_assignments (server_id);

-- [R9] An IP can only be attached to a server that is alive. The server row is locked
-- FOR SHARE, so this serialises with a concurrent termination (which locks it FOR UPDATE).
create function ip_assignments_server_alive() returns trigger
language plpgsql as $$
declare s server_status;
begin
  if upper_inf(new.during) then
    select status into s from servers where id = new.server_id for share;
    if s not in ('pending', 'provisioning', 'running') then
      raise exception 'cannot attach an IP to a % server', s using errcode = 'P0001';
    end if;
  end if;
  return new;
end $$;
create trigger ip_assignments_server_alive before insert on ip_assignments
  for each row execute function ip_assignments_server_alive();

-- ---------------------------------------------------------------------------
-- Ledger. The balance is sum(amount); rows are never updated or deleted [R10].
-- ---------------------------------------------------------------------------
create type ledger_kind as enum ('topup', 'charge', 'refund');

create table ledger_entries (
  id              bigserial primary key,
  customer_id     uuid not null references customers (id),
  kind            ledger_kind not null,
  amount          bigint not null,
  created_at      timestamptz not null default app_now(),
  description     text not null default '',
  idempotency_key text,
  refund_of       bigint,
  server_id       uuid references servers (id),
  ip_id           int references ip_addresses (id),
  holder_server_id uuid references servers (id),      -- for an IP charge: the server that held the IP in that hour
  hour_start      timestamptz,
  price_id        int references prices (id),
  billing_run_id  bigint,
  unique (id, customer_id),
  foreign key (refund_of, customer_id) references ledger_entries (id, customer_id),   -- a refund goes back to the same customer
  check (case kind
    when 'topup'  then amount > 0 and idempotency_key is not null and refund_of is null
    when 'refund' then amount > 0 and refund_of is not null
    when 'charge' then amount <= 0 and refund_of is null
  end),
  -- [R11] a charge is for exactly one resource and one whole hour; other kinds carry no resource
  check (case when kind = 'charge'
    then hour_start is not null and is_whole_hour(hour_start) and num_nonnulls(server_id, ip_id) = 1 and price_id is not null
         and (ip_id is null) = (holder_server_id is null)
    else hour_start is null and server_id is null and ip_id is null and price_id is null and holder_server_id is null
  end)
);
create index ledger_customer_idx on ledger_entries (customer_id, id);
create index ledger_holder_idx on ledger_entries (holder_server_id) where holder_server_id is not null;
create unique index ledger_topup_once on ledger_entries (customer_id, idempotency_key) where kind = 'topup';    -- [R12]
create unique index ledger_server_hour_once on ledger_entries (server_id, hour_start) where server_id is not null; -- [R13]
create unique index ledger_ip_hour_once on ledger_entries (ip_id, hour_start) where ip_id is not null;             -- [R14]
create unique index ledger_refund_once on ledger_entries (refund_of) where refund_of is not null;                   -- [R15]

create function ledger_append_only() returns trigger
language plpgsql as $$
begin
  raise exception 'ledger entries are append-only' using errcode = 'P0001';
end $$;
create trigger ledger_append_only before update or delete on ledger_entries
  for each row execute function ledger_append_only();
create trigger ledger_no_truncate before truncate on ledger_entries
  for each statement execute function ledger_append_only();

-- [R16] A refund returns exactly what a charge took.
create function ledger_refund_matches_charge() returns trigger
language plpgsql as $$
declare c ledger_entries;
begin
  if new.kind = 'refund' then
    select * into c from ledger_entries where id = new.refund_of;
    if c.kind <> 'charge' or new.amount <> -c.amount then
      raise exception 'a refund must return exactly one charge' using errcode = 'P0001';
    end if;
  end if;
  return new;
end $$;
create trigger ledger_refund_matches_charge before insert on ledger_entries
  for each row execute function ledger_refund_matches_charge();

create view customer_balances as
  select c.id as customer_id, coalesce(sum(l.amount), 0)::bigint as balance
  from customers c left join ledger_entries l on l.customer_id = c.id
  group by c.id;

-- ---------------------------------------------------------------------------
-- Billing runs and their failed items (for "one bad record" reporting)
-- ---------------------------------------------------------------------------
create table billing_runs (
  id              bigserial primary key,
  started_at      timestamptz not null default now(),
  finished_at     timestamptz,
  as_of           timestamptz not null,
  items_total     int not null default 0,
  items_failed    int not null default 0,
  charges_created int not null default 0
);
alter table ledger_entries add foreign key (billing_run_id) references billing_runs (id);

create table billing_failures (
  id          bigserial primary key,
  run_id      bigint not null references billing_runs (id),
  resource    resource_kind not null,
  resource_id text not null,
  error       text not null,
  at          timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Drift between our records and the infrastructure, found and repaired by the reconciler
-- ---------------------------------------------------------------------------
create table drift_events (
  id        bigserial primary key,
  at        timestamptz not null default now(),
  kind      text not null,
  server_id uuid references servers (id),
  infra_id  text,
  detail    text not null default ''
);

-- ---------------------------------------------------------------------------
-- Audit of staff actions
-- ---------------------------------------------------------------------------
create table audit_log (
  id         bigserial primary key,
  at         timestamptz not null default now(),
  app_time   timestamptz not null default app_now(),
  staff_id   uuid references staff_users (id),
  action     text not null,
  subject    text not null,
  detail     jsonb not null default '{}'
);
create index audit_subject_idx on audit_log (subject, id);
